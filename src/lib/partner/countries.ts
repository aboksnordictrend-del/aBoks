export type CountryCode = keyof typeof COUNTRY_NAMES_NB

export const COUNTRY_CODES = Object.keys(COUNTRY_NAMES_NB) as CountryCode[]

/** The default for a new referred customer. */
export const DEFAULT_COUNTRY_CODE: CountryCode = 'NO'

/** Shown first in the country picker, in this order; the rest follow alphabetically. */
const PINNED: readonly CountryCode[] = ['NO', 'SE', 'DK', 'FI', 'IS']

export function isCountryCode(value: unknown): value is CountryCode {
  return typeof value === 'string' && Object.prototype.hasOwnProperty.call(COUNTRY_NAMES_NB, value)
}

/**
 * Select options: «Norge (NO)» … Norway and the Nordic countries first, then every other country
 * sorted by its Norwegian name. The code is part of the label so a search for «SE» finds Sweden.
 */
export const COUNTRY_OPTIONS: { label: string; value: CountryCode }[] = [
  ...PINNED,
  ...COUNTRY_CODES.filter((code) => !PINNED.includes(code)).sort((a, b) =>
    COUNTRY_NAMES_NB[a].localeCompare(COUNTRY_NAMES_NB[b], 'nb'),
  ),
].map((code) => ({ label: `${COUNTRY_NAMES_NB[code]} (${code})`, value: code }))
