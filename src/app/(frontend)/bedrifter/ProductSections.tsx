/**
 * Document rows inside a solution card, one row per document. A row's first format claims
 * the whole row — icon, label and all — so clicking anywhere on it downloads the PDF. Any
 * further format (today only the Tilbudsmal's browser version) sits to its right as a
 * separate link, giving the `PDF ↓  HTML ↗` pairing.
 *
 * A row carrying an `anchor` instead of files (the Prisliste) keeps the same shape but
 * leads to the inquiry form, ending in `Be om tilbud →` where the others end in `PDF ↓`.
 */
function DocumentList({
  documents,
  productName,
  onAnchorClick,
}: {
  documents: ProductDocument[]
  productName: string
  /** Handles a click on an anchor row: presets the form and runs the scroll. */
  onAnchorClick: React.MouseEventHandler<HTMLAnchorElement>
}) {
  return (
    <div style={{ width: '100%', margin: '0 0 30px' }}>
      <p style={cardLabelStyle}>Dokumenter</p>
      <ul
        style={{
          listStyle: 'none',
          margin: 0,
          padding: 0,
          width: '100%',
          borderTop: `1px solid ${BORDER_WARM}`,
        }}
      >
        {documents.map((doc) => {
          const [primary, ...secondary] = doc.files
          return (
            <li
              key={doc.label}
              style={{ borderBottom: `1px solid ${BORDER_WARM}`, display: 'flex', alignItems: 'stretch' }}
            >
              {doc.anchor ? (
                <DocumentAnchorLink
                  anchor={doc.anchor}
                  documentLabel={doc.label}
                  productName={productName}
                  onClick={onAnchorClick}
                />
              ) : (
                <DocumentLink file={primary} documentLabel={doc.label} productName={productName} primary>
                  <FileIcon />
                  <span style={documentNameStyle}>{doc.label}</span>
                </DocumentLink>
              )}

              {secondary.map((file) => (
                <span key={file.type} style={{ display: 'flex', alignItems: 'stretch' }}>
                  <span
                    aria-hidden="true"
                    style={{ width: '1px', background: BORDER_WARM, margin: '9px 0', flexShrink: 0 }}
                  />
                  <DocumentLink file={file} documentLabel={doc.label} productName={productName} />
                </span>
              ))}
            </li>
          )
        })}
      </ul>
    </div>
  )
}

/**
 * One format of one document. `primary` makes it fill the remaining row width so the row
 * itself is the click target; otherwise it is a compact `HTML ↗` link at the end.
 *
 * PDFs download (the URL carries Blob's own `?download=1`), HTML opens in a new tab so the
 * customer can fill the template in and use its print button.
 */
function DocumentLink({
  file,
  documentLabel,
  productName,
  primary = false,
  children,
}: {
  file: DocumentFile
  documentLabel: string
  productName: string
  primary?: boolean
  children?: React.ReactNode
}) {
  const opens = file.action === 'open'
  return (
    <a
      href={file.url}
      data-btn
      className="abx-doc-row"
      {...(opens
        ? { target: '_blank', rel: 'noopener noreferrer' }
        : { download: true })}
      aria-label={
        opens
          ? `Åpne ${productName} ${documentLabel.toLowerCase()} i nettleseren`
          : `Last ned ${productName} ${documentLabel.toLowerCase()} som ${file.type}`
      }
      style={
        primary
          ? documentRowStyle
          : { ...documentRowStyle, gap: '7px', flex: '0 0 auto', padding: '12px 10px 12px 12px' }
      }
    >
      {children}
      <span className="abx-doc-type" style={fileTypeStyle}>
        {file.type}
      </span>
      {opens ? <ExternalLinkIcon /> : <DownloadIcon />}
    </a>
  )
}

/**
 * The Prisliste row. There is no public price sheet to download — the price depends on the
 * order — so the row keeps a file row's shape and sends the visitor to the inquiry form,
 * preselecting this product on the way.
 *
 * The `href` is a real in-page anchor, so a middle click, `/bedrifter#tilbud` typed by hand
 * and the no-JS case all still land on the form; `onClick` only takes over a plain left
 * click to run the site's own smooth scroll.
 */
function DocumentAnchorLink({
  anchor,
  documentLabel,
  productName,
  onClick,
}: {
  anchor: DocumentAnchor
  documentLabel: string
  productName: string
  onClick: React.MouseEventHandler<HTMLAnchorElement>
}) {
  return (
    <a
      href={`#${anchor.id}`}
      data-btn
      className="abx-doc-row"
      onClick={onClick}
      aria-label={`${documentLabel} for ${productName} — ${anchor.label.toLowerCase()} i skjemaet nedenfor`}
      style={documentRowStyle}
    >
      <FileIcon />
      <span style={documentNameStyle}>{documentLabel}</span>
      <span className="abx-doc-type" style={{ ...fileTypeStyle, whiteSpace: 'nowrap' }}>
        {anchor.label}
      </span>
      <ArrowRightIcon />
    </a>
  )
}

/**
 * One product's quantity prices.
 *
 * Every row is generated — see `BedrifterProduct.priceTable`. The last row is the quote row:
 * it carries the same unit price as the row above it, because reaching the quote threshold is
 * not a further reduction, and offers the enquiry instead of repeating the amount.
 */
function PriceTable({
  rows,
  productName,
  quoteHref,
  onQuoteRequest,
}: {
  rows: PriceTableRow[]
  productName: string
  /** Where the quote row points. A real anchor, so a middle click still lands somewhere. */
  quoteHref: string
  /** Presets the form with this product and the quote quantity, then scrolls to it. */
  onQuoteRequest: React.MouseEventHandler<HTMLAnchorElement>
}) {
  // A single open-ended row is a product with no quantity pricing — there is no table to show.
  if (rows.length < 2) return null
  // A product whose price could not be read would print a table of «kr 0». Better nothing.
  if (rows.some((row) => !(row.unitPrice > 0))) return null

  return (
    <div style={{ width: '100%', margin: '0 0 30px' }}>
      <p style={cardLabelStyle}>Pris per stk.</p>
      <table
        style={{
          width: '100%',
          borderCollapse: 'collapse',
          fontFamily: SANS,
          fontSize: '14.5px',
        }}
      >
        <caption className="sr-only">Mengdepriser for {productName}, eks. frakt</caption>
        <thead>
          <tr>
            <th
              scope="col"
              style={{
                textAlign: 'left',
                padding: '0 0 8px',
                fontWeight: 600,
                fontSize: '12.5px',
                letterSpacing: '0.04em',
                textTransform: 'uppercase',
                color: MUTED,
              }}
            >
              Antall
            </th>
            <th
              scope="col"
              style={{
                textAlign: 'right',
                padding: '0 0 8px',
                fontWeight: 600,
                fontSize: '12.5px',
                letterSpacing: '0.04em',
                textTransform: 'uppercase',
                color: MUTED,
              }}
            >
              Pris per stk.
            </th>
          </tr>
        </thead>
        <tbody>
          {rows.map((row) => (
            <tr key={row.range} style={{ borderTop: `1px solid ${BORDER_WARM}99` }}>
              <th
                scope="row"
                style={{ textAlign: 'left', padding: '11px 0', fontWeight: 600, color: INK }}
              >
                {row.range}
              </th>
              <td style={{ textAlign: 'right', padding: '11px 0', color: INK }}>
                {row.isQuoteRow ? (
                  // The published price still applies here — the link is an addition, not a
                  // replacement, and the amount is repeated so nothing looks withheld.
                  <span style={{ display: 'inline-flex', alignItems: 'baseline', gap: '10px', flexWrap: 'wrap', justifyContent: 'flex-end' }}>
                    <span style={{ color: MUTED }}>{formatPrice(row.unitPrice)}</span>
                    <a
                      href={quoteHref}
                      data-btn
                      onClick={onQuoteRequest}
                      style={{
                        fontWeight: 600,
                        color: OLIVE,
                        textDecoration: 'underline',
                        textUnderlineOffset: '3px',
                      }}
                    >
                      {QUOTE_TEXT.cta}
                    </a>
                  </span>
                ) : (
                  <span style={{ fontWeight: 600 }}>{formatPrice(row.unitPrice)}</span>
                )}
              </td>
            </tr>
          ))}
        </tbody>
      </table>
      <p
        style={{
          fontFamily: SANS,
          fontSize: '12.5px',
          lineHeight: 1.6,
          color: MUTED,
          margin: '10px 0 0',
        }}
      >
        Prisene er inkl. mva. og gjelder per produkt — antall av ulike produkter legges ikke
        sammen. Prisen gjelder alle enhetene i bestillingen.
      </p>
    </div>
  )
}

