/** One editorial product section. Every product on the page uses this shape. */
export interface ProductSection {
  name: string
  subtitle: string
  description: string
  suitableFor: string[]
  image: string
  imageAlt: string
  /** The catalogue photography is square. */
  imageAspect: string
  /** Product page the image links to. */
  href?: string
  /** Value the "Meld interesse" button presets in the form's dropdown. */
  interestOption: string
  /** Produktark, Prisliste and Tilbudsmal, resolved to the product's files in Blob. */
  documents: ProductDocument[]
  /**
   * The product's quantity price bands, generated by the shared pricing engine from its live
   * CMS price. There is deliberately no B2B price table written into this page — every figure
   * below comes from the same table the cart and the checkout charge from, so a price can
   * never be advertised here that the shop does not actually apply.
   *
   * A product with no configured bands gets a single open-ended row, which is the truth for
   * it, and no quote row.
   */
  priceTable: PriceTableRow[]
  /** The quantity the quote row's CTA asks about — the threshold itself. */
  quoteQuantity: number | null
}

