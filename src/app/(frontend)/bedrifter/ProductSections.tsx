/** A product section together with the catalogue entry it was built from. */
export type BedrifterProductSection = ProductSection & { product: BedrifterProduct }

/**
 * Every product handed in, as an editorial section, in the order they arrive. Each entry
 * carries its own product page, so its photo links there.
 *
 * The one place a `BedrifterProduct` becomes a section: /bedrifter builds the whole
 * catalogue this way and a package page builds its own products, so neither can drift.
 */
export function buildProductSections(products: BedrifterProduct[]): BedrifterProductSection[] {
  return products.map((product) => {
    const copy = CATALOGUE_COPY[product.slug]
    // A future CMS product with no files in the Blob folder simply renders without the
    // "Dokumenter" block rather than with links that 404.
    const documentKey = bedrifterProductKey(product.slug)
    return {
      product,
      // Generated from the shared engine, never restated here. The quote row's quantity is
      // the threshold itself, so the enquiry it opens asks about the quantity it names.
      priceTable: buildPriceTableRows(product),
      quoteQuantity: quoteThresholdFor(product),
      name: product.title,
      subtitle: copy?.subtitle ?? product.tagline,
      description: copy?.description ?? (product.description || product.tagline),
      suitableFor: copy?.suitableFor ?? [],
      image: product.image,
      imageAlt: product.imageAlt,
      // The catalogue photography is square — a 4:3 crop would cut into the products.
      imageAspect: '1 / 1',
      href: `/produkter/${product.slug}`,
      // The form's dropdown carries a per-model option only for some of the catalogue.
      interestOption: copy?.interestOption ?? 'Produkter til egen bedrift',
      documents: documentKey ? bedrifterDocuments(documentKey) : [],
    }
  })
}

/**
 * The sections one after another, sides alternating, with the rules they need rendered
 * once above them.
 *
 * Each handler is a factory taking the section, because every button acts on the product it
 * belongs to. The page decides what a click does — which form it fills and which anchor it
 * scrolls to — so /bedrifter keeps its own behaviour and a package page can send the same
 * buttons to its own inquiry form.
 */
export default function ProductSectionList({
  sections,
  reveal,
  quoteHref = '#tilbud',
  withAnchorIds = false,
  onInterest,
  onDocumentRequest,
  onPriceTableQuote,
}: {
  sections: BedrifterProductSection[]
  reveal: (delay?: number) => RevealProps
  /**
   * Where the price tables' quote rows point. The default is /bedrifter's own `#tilbud`
   * block; a page whose form sits behind a different anchor passes its own, so the link is
   * never a hash that page does not have.
   */
  quoteHref?: string
  /**
   * Gives every section the `id` `productSectionAnchorId` derives from its slug, so the
   * page can link down to it. A package page turns this on for its configurator's
   * "Se produktdetaljer" links; /bedrifter has nothing linking to its sections and leaves
   * them as they are.
   */
  withAnchorIds?: boolean
  /** "Meld interesse" — the form's dropdown, preset to this product. */
  onInterest: (section: BedrifterProductSection) => React.MouseEventHandler<HTMLAnchorElement>
  /** A document row that asks for something instead of handing over a file. */
  onDocumentRequest: (section: BedrifterProductSection) => React.MouseEventHandler<HTMLAnchorElement>
  /** The price table's quote row — the product and the quantity it names. */
  onPriceTableQuote: (section: BedrifterProductSection) => React.MouseEventHandler<HTMLAnchorElement>
}) {
  return (
    <>
      <style>{PRODUCT_SECTION_CSS}</style>
      <div style={{ display: 'flex', flexDirection: 'column', gap: 'clamp(64px,8vw,112px)' }}>
        {sections.map((section, index) => (
          <ProductSectionBlock
            key={section.name}
            section={section}
            anchorId={withAnchorIds ? productSectionAnchorId(section.product.slug) : undefined}
            imageFirst={index % 2 === 0}
            reveal={reveal}
            quoteHref={quoteHref}
            onInterest={onInterest(section)}
            onDocumentRequest={onDocumentRequest(section)}
            onPriceTableQuote={onPriceTableQuote(section)}
          />
        ))}
      </div>
    </>
  )
}
